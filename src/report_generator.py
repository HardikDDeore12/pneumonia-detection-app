from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_pdf_report(report_path, original_img_path, heatmap_img_path, result, confidence):
    doc = SimpleDocTemplate(report_path, pagesize=letter, rightMargin=30, leftMargin=30, topMargin=30, bottomMargin=30)
    story = []
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'ReportTitle',
        parent=styles['Heading1'],
        fontSize=20,
        textColor=colors.HexColor("#1A365D"),
        spaceAfter=5,
        alignment=1
    )
    
    subtitle_style = ParagraphStyle(
        'ReportSubtitle',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor("#718096"),
        spaceAfter=15,
        alignment=1
    )

    story.append(Paragraph("AI Clinical Diagnostic Report", title_style))
    story.append(Paragraph("Chest X-Ray Pneumonia Screening System", subtitle_style))
    story.append(Spacer(1, 10))

    # Summary Table
    summary_data = [
        [Paragraph("<b>Diagnostic Result:</b>", styles['Normal']), Paragraph(f"<b>{result}</b>", styles['Normal'])],
        [Paragraph("<b>Confidence Score:</b>", styles['Normal']), Paragraph(f"{confidence}%", styles['Normal'])],
        [Paragraph("<b>Status:</b>", styles['Normal']), Paragraph("Review Required by Physician", styles['Normal'])]
    ]
    
    t = Table(summary_data, colWidths=[150, 350])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#EDF2F7")),
        ('PADDING', (0,0), (-1,-1), 8),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CBD5E0"))
    ]))
    story.append(t)
    story.append(Spacer(1, 15))

    # --- NEW: Detailed Image Analysis / Explanation Section ---
    story.append(Paragraph("<b>Clinical Image Analysis & Findings</b>", styles['Heading3']))
    story.append(Spacer(1, 5))
    
    if "Pneumonia" in result:
        explanation_text = (
            f"The deep learning screening model analyzed the chest radiograph and identified patterns "
            f"consistent with pulmonary infection (Pneumonia) with a high confidence score of <b>{confidence}%</b>. "
            f"Visual inspection via Grad-CAM attention mapping highlights regions exhibiting diffuse opacities, "
            f"infiltrates, or cellular exudate accumulation within the lung parenchyma. Immediate clinical correlation "
            f"and physical examination are recommended."
        )
    else:
        explanation_text = (
            f"The deep learning screening model evaluated the chest radiograph and classified the scan as "
            f"<b>Normal</b> with a confidence score of <b>{confidence}%</b>. "
            f"The lung fields appear clear without significant focal consolidations, interstitial markings, "
            f"or pleural effusion. Routine follow-up is advised if symptoms persist."
        )
    
    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor("#2D3748"),
        leading=14
    )
    story.append(Paragraph(explanation_text, body_style))
    story.append(Spacer(1, 15))

    # Visual Scan Section
    story.append(Paragraph("<b>Visual Scan Comparison (Original vs. Grad-CAM Heatmap)</b>", styles['Heading3']))
    story.append(Spacer(1, 8))

    img_table = Table([
        [Image(original_img_path, width=180, height=180), Image(heatmap_img_path, width=180, height=180)],
        [Paragraph("Original X-Ray", styles['Normal']), Paragraph("Grad-CAM Heatmap", styles['Normal'])]
    ], colWidths=[250, 250])
    
    img_table.setStyle(TableStyle([
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
    ]))
    story.append(img_table)
    story.append(Spacer(1, 20))

    # Disclaimer
    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Italic'],
        fontSize=8,
        textColor=colors.HexColor("#A0AEC0"),
        alignment=1
    )
    story.append(Paragraph("Disclaimer: This report is generated by an automated deep learning screening model and should not be used as a definitive clinical diagnosis. Always consult a qualified medical professional.", disclaimer_style))

    doc.build(story)
    return report_path